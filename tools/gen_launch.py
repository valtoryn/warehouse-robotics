#!/usr/bin/env python3
"""Generate ROS 2 launch and parameter artifacts from a Valtoryn robot config.

Phase 2 scaffolding: emits, for a given robot config,
  * <name>_controllers.yaml  — ros2_control controller parameters
  * <name>_nav2.yaml         — Nav2 parameter stub (placeholder values; real
                               tuning is Phase 3 work per SIMULATION_REQUIREMENTS)
  * <name>_launch.py         — launch skeleton bringing up robot_state_publisher,
                               controller_manager and the diff_drive controller

Generated files are build artifacts (see generated/, git-ignored). The launch
file targets the pinned ROS distro once TD-2 is decided; the structure follows
standard ros2_control bring-up and is distro-agnostic.

Usage:
  python tools/gen_launch.py config/robots/ref-amr-diff-v1.yaml --out-dir generated/
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml


def fmt(v: float) -> str:
    return f"{v:.6f}".rstrip("0").rstrip(".") or "0"


def controller_params(config: dict) -> str:
    ch = next(m for m in config["modules"] if m["type"].endswith("chassis.differential"))
    p = ch.get("parameters", {})
    sep = float(p.get("wheel_separation", 0.6))
    wr = float(p.get("wheel_radius", 0.075))
    v = float(p.get("max_linear_velocity", 1.2))
    w = float(p.get("max_angular_velocity", 1.5))
    return f"""# Generated by tools/gen_launch.py — do not edit.
controller_manager:
  ros__parameters:
    update_rate: 50  # Hz [EST] — controller_manager rate; verify against chassis requirements
    diff_drive_controller:
      type: diff_drive_controller/DiffDriveController
    joint_state_broadcaster:
      type: joint_state_broadcaster/JointStateBroadcaster

diff_drive_controller:
  ros__parameters:
    left_wheel_names: ["wheel_fl_joint", "wheel_rl_joint"]
    right_wheel_names: ["wheel_fr_joint", "wheel_rr_joint"]
    wheel_separation: {fmt(sep)}
    wheel_radius: {fmt(wr)}
    wheel_separation_multiplier: 1.0
    left_wheel_radius_multiplier: 1.0
    right_wheel_radius_multiplier: 1.0
    publish_rate: 50.0
    use_stamped_vel: true
    cmd_vel_timeout: 0.5
    base_frame_id: base_link
    odom_frame_id: odom
    pose_covariance_diagonal: [0.001, 0.001, 0.01, 0.01, 0.01, 0.05]
    twist_covariance_diagonal: [0.01, 0.01, 0.01, 0.01, 0.01, 0.05]
"""


def nav2_params(config: dict) -> str:
    ch = next(m for m in config["modules"] if m["type"].endswith("chassis.differential"))
    p = ch.get("parameters", {})
    v = float(p.get("max_linear_velocity", 1.2))
    w = float(p.get("max_angular_velocity", 1.5))
    return f"""# Generated by tools/gen_launch.py — STUB. Nav2 tuning is Phase 3 work
# (docs/engineering/SIMULATION_REQUIREMENTS.md); values below are placeholders.
controller_server:
  ros__parameters:
    controller_frequency: 10.0
    min_x_velocity_threshold: 0.001
    min_y_velocity_threshold: 0.5
    min_theta_velocity_threshold: 0.001
    failure_tolerance: 0.3
    progress_checker_plugin: "progress_checker"
    goal_checker_plugins: ["general_goal_checker"]
    controller_plugins: ["FollowPath"]
    progress_checker:
      plugin: "nav2_controller::SimpleProgressChecker"
      required_movement_radius: 0.5
      movement_time_allowance: 10.0
    general_goal_checker:
      stateful: true
      plugin: "nav2_controller::SimpleGoalChecker"
      xy_goal_tolerance: 0.05
      yaw_goal_tolerance: 0.1
    FollowPath:
      plugin: "nav2_regulated_pure_pursuit_controller::RegulatedPurePursuitController"
      desired_linear_vel: {fmt(v)}
      lookahead_dist: 0.6
      max_angular_accel: {fmt(3.0 * w)}
bt_navigator:
  ros__parameters:
    global_frame: odom
    robot_base_frame: base_link
    odom_topic: /odom
planner_server:
  ros__parameters:
    expected_planner_frequency: 5.0
    planner_plugins: ["GridBased"]
    GridBased:
      plugin: "nav2_navfn_planner/NavfnPlanner"
      tolerance: 0.5
      use_astar: false
      allow_unknown: true
"""


def launch_py(config: dict, urdf_name: str) -> str:
    rid = config["robot"]["id"]
    return f'''#!/usr/bin/env python3
# Generated by tools/gen_launch.py — do not edit.
# Skeleton bring-up for '{rid}'. Requires the pinned ROS distro (TD-2) and the
# generated URDF from tools/gen_urdf.py. Controller spawner names follow the
# standard ros2_control pattern.

from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def _launch(context, *args, **kwargs):
    urdf_path = LaunchConfiguration("urdf_path").perform(context)
    params_path = LaunchConfiguration("params_path").perform(context)

    robot_state_publisher = Node(
        package="robot_state_publisher",
        executable="robot_state_publisher",
        parameters=[urdf_path],
        output="screen",
    )

    controller_manager = Node(
        package="controller_manager",
        executable="ros2_control_node",
        parameters=[urdf_path, params_path],
        output="screen",
    )

    # Spawners are launched once the controller manager is up; sequencing via
    # lifecycle events lands with the Phase 2 lifecycle supervisor.
    jsb_spawner = Node(
        package="controller_manager",
        executable="spawner",
        arguments=["joint_state_broadcaster"],
        output="screen",
    )
    ddc_spawner = Node(
        package="controller_manager",
        executable="spawner",
        arguments=["diff_drive_controller"],
        output="screen",
    )

    return [robot_state_publisher, controller_manager, jsb_spawner, ddc_spawner]


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument("urdf_path"),
        DeclareLaunchArgument("params_path"),
        OpaqueFunction(function=_launch),
    ])
'''


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    cfg_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[sys.argv.index("--out-dir") + 1]) if "--out-dir" in sys.argv else Path("generated")
    config = yaml.safe_load(cfg_path.read_text(encoding="utf-8"))
    name = cfg_path.stem
    out_dir.mkdir(parents=True, exist_ok=True)

    (out_dir / f"{name}_controllers.yaml").write_text(controller_params(config), encoding="utf-8")
    (out_dir / f"{name}_nav2.yaml").write_text(nav2_params(config), encoding="utf-8")
    (out_dir / f"{name}_launch.py").write_text(launch_py(config, name), encoding="utf-8")
    print(f"wrote {name}_controllers.yaml, {name}_nav2.yaml, {name}_launch.py to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
